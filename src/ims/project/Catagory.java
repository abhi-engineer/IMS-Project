    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) catagoryTable.getModel();

        if (validateForm()) {
            String catagory = catagoryField.getText();
            rowIndex = catagoryTable.getSelectedRow();

            String idd = model.getValueAt(rowIndex, 0).toString();
            int id = Integer.parseInt(idd);
            try {
                query = "UPDATE CatagoryTable SET Catagory = ? WHERE Id = " + id;
                PreparedStatement ps = con.prepareStatement(query);
                ps.setString(1, catagory);
                ps.executeUpdate();

                updateItem(rowIndex, id);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_updateBtnActionPerformed

