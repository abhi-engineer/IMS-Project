    //adding new item into the display table;
    private void addItemInTable(String catagory) {
    DefaultTableModel model = (DefaultTableModel) catagoryTable.getModel();
    try {
        query = "SELECT * from CatagoryTable WHERE Catagory = ?";
        PreparedStatement ps = con.prepareStatement(query);
        ps.setString(1, catagory);
        ResultSet set = ps.executeQuery();
        while (set.next()) {
            model.addRow(new Object[]{set.getString("Id"), set.getString("Catagory")});
            JOptionPane.showMessageDialog(null, catagory + " added sucessfully");
            catagoryField.setText("");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }

}

    private void updateItem(int rowIndex, int id) {
    DefaultTableModel model = (DefaultTableModel) catagoryTable.getModel();
    try {
        query = "SELECT * FROM CatagoryTable WHERE Id = ?";
        PreparedStatement ps = con.prepareStatement(query);
        ps.setInt(1, id);
        ResultSet set = ps.executeQuery();

        if (set.next()) {
            model.setValueAt(set.getInt("Id"), rowIndex, 0);
            model.setValueAt(set.getString("Catagory"), rowIndex, 1);
        }
        JOptionPane.showMessageDialog(null, id + " Updated sucessfully");
        catagoryField.setText("");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e);
    }
    updateBtn.setEnabled(false);
    deleteBtn.setEnabled(false);
    saveBtn.setEnabled(true);
}

