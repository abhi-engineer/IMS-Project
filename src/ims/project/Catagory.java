    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) catagoryTable.getModel();
        rowIndex = catagoryTable.getSelectedRow();

        String idd = model.getValueAt(rowIndex, 0).toString();
        int id = Integer.parseInt(idd);

        if (rowIndex >= 0) {
            int i = JOptionPane.showConfirmDialog(null, "Do you want to delete Id " + id, "Select", JOptionPane.YES_NO_OPTION);
            if (i == 0) {
                try {
                    query = "DELETE FROM CatagoryTable WHERE Id = " + id;
                    PreparedStatement ps = con.prepareStatement(query);
                    ps.executeUpdate();

                    model.removeRow(rowIndex);
                    JOptionPane.showMessageDialog(null, "Id " + id + " deleted sucessfully");

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, e);
                }
            }
        }
        catagoryField.setText("");
        saveBtn.setEnabled(true);
        deleteBtn.setEnabled(false);
        updateBtn.setEnabled(false);
    }//GEN-LAST:event_deleteBtnActionPerformed

