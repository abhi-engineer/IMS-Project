    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:

        if (validateForm()) {
            String name = nameField.getText();
            int quantity = Integer.parseInt(quantityField.getText());
            float price = Float.parseFloat(priceField.getText());
            String description = descriptionField.getText();
            String catagory = catagoryBox.getSelectedItem().toString();
            String catagoryId[] = catagory.split("-", 0);// 0 limit on index;

            try {
                query = "INSERT INTO ProductTable (name,quantity,price,description,catagory_id) VALUES(?,?,?,?,?)";
                PreparedStatement ps = con.prepareStatement(query);
                ps.setString(1, name);
                ps.setInt(2, quantity);
                ps.setFloat(3, price);
                ps.setString(4, description);
                ps.setString(5, catagoryId[0]);
                ps.executeUpdate();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, e);
            }

            resetFields();

            addItemInTable(catagoryId[0], name);
            
            JOptionPane.showMessageDialog(null, name+" added successfully");
            saveBtn.setEnabled(true);
        } else {
            JOptionPane.showMessageDialog(null, "Fill all fields");
        }
    }//GEN-LAST:event_saveBtnActionPerformed

