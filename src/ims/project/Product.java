    private void addItemInTable(String catagoryId, String name) {
        DefaultTableModel model = (DefaultTableModel) productTable.getModel();
        try {
            query = "SELECT * FROM ProductTable INNER JOIN CatagoryTable ON ProductTable.catagory_id = CatagoryTable.id WHERE catagory_id = ? AND name = ?";
            PreparedStatement ps = con.prepareStatement(query);
            ps.setString(1, catagoryId);
            ps.setString(2, name);
            ResultSet set = ps.executeQuery();
            if (set.next()) {
                model.addRow(new Object[]{set.getString("id"), set.getString("name"), set.getInt("quantity"), set.getFloat("price"), set.getString("description"), set.getInt("catagory_id"), set.getString(8)});
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

    private void updateItem(int rowIndex, int id) {
        DefaultTableModel model = (DefaultTableModel) productTable.getModel();

        try {
            query = "SELECT * FROM ProductTable where id = ?";
            PreparedStatement ps = con.prepareStatement(query);
            ps.setInt(1, id);
            ResultSet set = ps.executeQuery();
            if (set.next()) {
                model.setValueAt(set.getInt("id"), rowIndex, 0);
                model.setValueAt(set.getString("name"), rowIndex, 1);
                model.setValueAt(set.getInt("quantity"), rowIndex, 2);
                model.setValueAt(set.getFloat("price"), rowIndex, 3);
                model.setValueAt(set.getString("description"), rowIndex, 4);
                model.setValueAt(set.getInt("id"), rowIndex, 5);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

