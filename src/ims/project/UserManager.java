    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:
        if (validateForm()) {
            String name = namefield.getText();
            String phone = phonefield.getText();
            String email = emailfield.getText();
            String address = addressfield.getText();
            String status = (String) statusbox.getSelectedItem();
            char[] ch = passwordfield.getPassword();
            String password = new String(ch);

            try {
                String query2 = "INSERT into appuser(userRole,name,mobileNumber,email,password,address,status) VALUES('Admin',?,?,?,?,?,?)";
                PreparedStatement ps = con.prepareStatement(query2);
                ps.setString(1, name);
                ps.setString(2, phone);
                ps.setString(3, email);
                ps.setString(4, password);
                ps.setString(5, address);
                ps.setString(6, status);

                int i = ps.executeUpdate();
                if (i > 0) {
                    JOptionPane.showMessageDialog(null, name + " added successfully");
//                    this.dispose();
//                    new UserManager().setVisible(true);
                    addItemInTable(phone, email);
                } else {
                    JOptionPane.showMessageDialog(null, name + " not added");
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        } else {
            JOptionPane.showMessageDialog(null, "Fill all fields");
        }
        resetFields();
    }//GEN-LAST:event_saveBtnActionPerformed

