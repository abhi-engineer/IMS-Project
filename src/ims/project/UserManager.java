    //add items in the display table on screen
    private void addItemInTable(String phone, String email) {
        DefaultTableModel model = (DefaultTableModel) userTable.getModel();

        // Ensure connection object is valid
        if (con == null) {
            JOptionPane.showMessageDialog(null, "Database connection is not initialized.");
            return;
        }

        try {
            // Use a parameterized query to prevent SQL injection
            String query1 = "SELECT * FROM appuser WHERE mobileNumber = ? AND email = ?";
            PreparedStatement ps = con.prepareStatement(query1);
            ps.setString(1, phone);
            ps.setString(2, email);

            ResultSet set = ps.executeQuery();

            // Iterate through the result set
            while (set.next()) {
                // Add each row to the table
                model.addRow(new Object[]{
                    set.getInt("appuser_pk"), // Primary key
                    set.getString("name"), // Name
                    set.getString("mobileNumber"), // Mobile Number
                    set.getString("email"), // Email
                    set.getString("address"), // Address
                    set.getString("status"), // Status
                    set.getString("password") // Password
                });
            }

        } catch (Exception e) {
            // Show the error in a dialog box
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }

    //update table on the display
    private void updateTable(int rowIndex, int appuserPk) {
        DefaultTableModel model = (DefaultTableModel) userTable.getModel();

        // Ensure the database connection is valid
        if (con == null) {
            JOptionPane.showMessageDialog(null, "Database connection is not initialized.");
            return;
        }

        try {
            // Use a parameterized query to get data
            String query1 = "SELECT * FROM appuser WHERE appuser_pk = ?";
            PreparedStatement ps = con.prepareStatement(query1);
            ps.setInt(1, appuserPk);
            ResultSet set = ps.executeQuery();

            // Check if the result set has data
            if (set.next()) {
                // Update the table row
                model.setValueAt(set.getInt("appuser_pk"), rowIndex, 0); // Column index adjusted to start from 0
                model.setValueAt(set.getString("name"), rowIndex, 1);
                model.setValueAt(set.getString("mobileNumber"), rowIndex, 2);
                model.setValueAt(set.getString("email"), rowIndex, 3);
                model.setValueAt(set.getString("address"), rowIndex, 4);
                model.setValueAt(set.getString("status"), rowIndex, 5);
                model.setValueAt(set.getString("password"), rowIndex, 6);
            } else {
                JOptionPane.showMessageDialog(null, "No data found for appuser_pk: " + appuserPk);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error updating table: " + e.getMessage());
        }

        resetFields();
        // Optionally disable the button
        updateBtn.setEnabled(false);
        deleteBtn.setEnabled(false);
    }

