    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        // TODO add your handling code here:
        if (validateForm()) {
            int index = userTable.getSelectedRow();
            TableModel model = userTable.getModel();

            String name = namefield.getText();
            String phone = phonefield.getText();
            String email = emailfield.getText();
            String address = addressfield.getText();
            String status = (String) statusbox.getSelectedItem();
            char[] ch = passwordfield.getPassword();
            String password = new String(ch);

            String id = model.getValueAt(index, 0).toString();
            appuserPk = Integer.parseInt(id);

            try {
                String query2 = "UPDATE appuser set name=?,mobileNumber=?,email=?,password=?,address=?,status=? WHERE appuser_pk=?";
                PreparedStatement ps = con.prepareStatement(query2);
                ps.setString(1, name);
                ps.setString(2, phone);
                ps.setString(3, email);
                ps.setString(4, password);
                ps.setString(5, address);
                ps.setString(6, status);
                ps.setInt(7, appuserPk);

                int i = ps.executeUpdate();
                if (i > 0) {
                    JOptionPane.showMessageDialog(null, name + " Updated sucessfully");
//                    this.dispose();
//                    new UserManager().setVisible(true);
                    rowIndex = userTable.getSelectedRow();
                    updateTable(rowIndex, appuserPk);
                } else {
                    JOptionPane.showMessageDialog(null, name + " not Updated");
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Fill all fields");
        }
    }//GEN-LAST:event_updateBtnActionPerformed

